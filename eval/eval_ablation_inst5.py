"""
Ablation Study Unified Evaluation (n_instance = 5)
===================================================
Unified evaluation for V0-V5 six variants, metrics consistent with ablation_study_design.md:
    P@1, P@3, P@5, MRR, Recall@GT

Variant -> Result File Mapping (relative to data/<Dataset>/res/<target>/)
-------------------------------------------------------------------------
  V0  Full ProDSM     : inst5/updated_sim_matrix_iter5_p2_k13_d4_c15.json  (exists)
  V1  w/o ADVR        : inst5/sim_matrix.json                               (exists)
  V2  w/o IND-Graph   : inst5_noind/sim_matrix.json                         (generated by DepySM_ablation)
  V3  Random Bridge   : inst5_randbr/updated_sim_matrix_iter5_p2_k13_d4_c15.json (same)
  V4  FD-only         : inst5/updated_sim_matrix_fd_only.json               (same)
  V5  IND-only        : inst5/updated_sim_matrix_ind_only.json              (same)

Ground Truth: data/<Dataset>/res/<target>/ground_true.json

Consistency Check Note
----------------------
  MusicRecordings has no IND: V2 (no IND graph edges) and V5 (IND-only ADVR) matrices
  should be element-wise equal to V1 (inst5/sim_matrix.json); eval will auto-notify on read.

Usage (under eval/ directory)
-----------------------------
    cd eval
    python eval_ablation_inst5.py
"""

import json
import os

import numpy as np

# -- Configuration -----------------------------------------------------------
BASE = "../data"   # run from eval/ directory

DATASETS = {
    "MusicRecordings": [f"target{i}" for i in range(1, 7)],
    "Movielens":       [f"target{i}" for i in range(1, 7)],
    "TPCH":            [f"target{i}" for i in range(1, 9)],
}

# No-IND datasets: V2/V5 should be equal to V1 (consistency check)
NO_IND_DATASETS = {"MusicRecordings"}

VARIANTS = ["V0", "V1", "V2", "V3", "V4", "V5"]

VARIANT_LABELS = {
    "V0": "V0 Full ProDSM",
    "V1": "V1 w/o ADVR",
    "V2": "V2 w/o IND-Graph",
    "V3": "V3 Random Bridge",
    "V4": "V4 FD-only",
    "V5": "V5 IND-only",
}

# (inst subdirectory, filename)  <- semantic naming, independent of numbering
VARIANT_FILES = {
    "V0": ("inst5",        "updated_sim_matrix_iter5_p2_k13_d4_c15.json"),
    "V1": ("inst5",        "sim_matrix.json"),
    "V2": ("inst5_noind",  "sim_matrix.json"),
    "V3": ("inst5_randbr", "updated_sim_matrix_iter5_p2_k13_d4_c15.json"),
    "V4": ("inst5",        "updated_sim_matrix_fd_only.json"),
    "V5": ("inst5",        "updated_sim_matrix_ind_only.json"),
}

# On no-IND datasets, which variants should fall back to V1 (fallback)
V1_FALLBACK_VARIANTS = {"V2", "V5"}   # when no IND: V2==V1, V5==V1

TOPK = [1, 3, 5]
METRIC_KEYS   = [f"p@{k}" for k in TOPK] + ["mrr", "recall"]
METRIC_LABELS = {**{f"p@{k}": f"P@{k}" for k in TOPK},
                 "mrr": "MRR", "recall": "Recall@GT"}


# ==================================================================
# Metric implementation (identical to eval_depysm_all_inst.py, ensuring numerical comparability with V0/V1)
# ==================================================================

def precision_topk(sim_matrix, gt_has_match, gt_indices, k):
    """For each target column, select the top-k source columns with highest similarity; correct if any hits GT."""
    topk_idx = np.argsort(sim_matrix, axis=1)[:, -k:]
    correct   = sum(
        1 for i in range(sim_matrix.shape[0])
        if gt_has_match[i] and any(idx in gt_indices[i] for idx in topk_idx[i])
    )
    denom = float(gt_has_match.sum())
    return correct, (correct / denom if denom > 0 else 0.0)


def compute_mrr(sim_matrix, gt_has_match, gt_indices):
    """Reciprocal rank of the first GT hit per target column, averaged across columns with GT."""
    rr_sum, valid = 0.0, 0
    for i in range(sim_matrix.shape[0]):
        if not gt_has_match[i]:
            continue
        for rank, col in enumerate(np.argsort(sim_matrix[i])[::-1], start=1):
            if col in gt_indices[i]:
                rr_sum += 1.0 / rank
                break
        valid += 1
    return rr_sum / valid if valid > 0 else 0.0


def compute_recall_at_gt(sim_matrix, gt_has_match, gt_indices):
    """
    Recall@GT: Let |G| be the total number of GT (target, source) pairs.
    Select the top |G| highest-scoring pairs from the entire matrix and compute the fraction that falls in G.
    """
    G = {
        (i, col)
        for i in range(sim_matrix.shape[0])
        if gt_has_match[i]
        for col in gt_indices[i]
    }
    k = len(G)
    if k == 0:
        return 0.0
    rows, cols = np.unravel_index(
        np.argsort(sim_matrix, axis=None)[::-1], sim_matrix.shape)
    top_k = set(zip(rows[:k].tolist(), cols[:k].tolist()))
    return len(G & top_k) / k


def gt_json_to_matrix(gt_json, n_source_cols):
    """GT JSON -> 0/1 matrix, rows=target columns (in JSON order), columns=source global IDs."""
    gt_matrix = np.zeros((len(gt_json), n_source_cols), dtype=int)
    for i, (_, src_indices) in enumerate(gt_json.items()):
        for src_idx in src_indices:
            if 0 <= src_idx < n_source_cols:
                gt_matrix[i, src_idx] = 1
            else:
                print(f"    [warn] GT source column ID {src_idx} exceeds matrix width {n_source_cols}, ignored")
    return gt_matrix


# ==================================================================
# Single matrix -> metrics
# ==================================================================

def metrics_for_matrix(mat, gt_json):
    """n_source is auto-inferred from similarity matrix width, no hardcoding needed."""
    n_source = mat.shape[1]
    gt       = gt_json_to_matrix(gt_json, n_source)
    gt_has   = gt.max(axis=1) == 1
    gt_idx   = [set(np.where(gt[i] == 1)[0]) for i in range(gt.shape[0])]
    out = {f"p@{k}": precision_topk(mat, gt_has, gt_idx, k)[1] for k in TOPK}
    out["mrr"]    = compute_mrr(mat, gt_has, gt_idx)
    out["recall"] = compute_recall_at_gt(mat, gt_has, gt_idx)
    return out


# ==================================================================
# File loading
# ==================================================================

def load_variant_matrix(data, target, variant):
    """
    Load the similarity matrix for a given variant.
    For no-IND datasets (MusicRecordings), fall back to V1 if V2/V5 files are missing.
    Returns (np.ndarray or None, actual read path).
    """
    sub, fname = VARIANT_FILES[variant]
    path = f"{BASE}/{data}/res/{target}/{sub}/{fname}"

    if not os.path.exists(path):
        # On no-IND datasets, V2/V5 should theoretically equal V1, provide fallback
        if variant in V1_FALLBACK_VARIANTS and data in NO_IND_DATASETS:
            v1_sub, v1_fname = VARIANT_FILES["V1"]
            v1_path = f"{BASE}/{data}/res/{target}/{v1_sub}/{v1_fname}"
            if os.path.exists(v1_path):
                print(f"    [info] {data}/{target} {VARIANT_LABELS[variant]} "
                      f"file missing, falling back to V1 (no IND dataset, theoretically equivalent)")
                return np.array(json.load(open(v1_path, encoding="utf-8"))), v1_path
        return None, path

    mat = np.array(json.load(open(path, encoding="utf-8")))

    # Consistency check: on no-IND datasets V2/V5 should equal V1
    if variant in V1_FALLBACK_VARIANTS and data in NO_IND_DATASETS:
        v1_sub, v1_fname = VARIANT_FILES["V1"]
        v1_path = f"{BASE}/{data}/res/{target}/{v1_sub}/{v1_fname}"
        if os.path.exists(v1_path):
            v1 = np.array(json.load(open(v1_path, encoding="utf-8")))
            same = np.allclose(mat, v1)
            tag  = "OK" if same else "FAIL - please check"
            print(f"    [consistency] {data}/{target} {VARIANT_LABELS[variant]} == V1: {tag}")

    return mat, path


def load_ground_truth(data, target):
    gt_path = f"{BASE}/{data}/res/{target}/ground_true.json"
    if not os.path.exists(gt_path):
        return None
    return json.load(open(gt_path, encoding="utf-8"))


# ==================================================================
# Main evaluation pipeline
# ==================================================================

def evaluate_all():
    """
    Iterate over all datasets / targets / variants, computing P@1/P@3/P@5/MRR/Recall@GT.
    Returns results[data][variant][target] = {metric: value}.
    """
    results = {d: {v: {} for v in VARIANTS} for d in DATASETS}

    for data, targets in DATASETS.items():
        print(f"\n{'=' * 80}\n  Dataset: {data}\n{'=' * 80}")
        for target in targets:
            gt_json = load_ground_truth(data, target)
            if gt_json is None:
                print(f"  [skip] {target}: missing ground_true.json")
                continue
            print(f"\n  --- {target} ---")
            for v in VARIANTS:
                mat, path = load_variant_matrix(data, target, v)
                if mat is None:
                    print(f"    {VARIANT_LABELS[v]:<22} [skip] missing {path}")
                    continue
                m = metrics_for_matrix(mat, gt_json)
                results[data][v][target] = m
                line = "  ".join(f"{METRIC_LABELS[k]}={m[k]:.4f}" for k in METRIC_KEYS)
                print(f"    {VARIANT_LABELS[v]:<22} {line}")

    return results


# ==================================================================
# Output: per-dataset average table + ablation comparison table
# ==================================================================

def print_per_dataset_avg(results):
    """Per dataset: variant x metric average table across targets."""
    for data in DATASETS:
        print(f"\n{'=' * 80}\n  {data} -- Average across targets per variant\n{'=' * 80}")
        hdr = f"  {'Variant':<22}" + "".join(f"{METRIC_LABELS[k]:>12}" for k in METRIC_KEYS)
        print(hdr)
        print("  " + "-" * (len(hdr) - 2))
        for v in VARIANTS:
            per_t = results[data][v]
            if not per_t:
                print(f"  {VARIANT_LABELS[v]:<22}" + f"{'N/A':>12}" * len(METRIC_KEYS))
                continue
            avg = {k: float(np.mean([per_t[t][k] for t in per_t])) for k in METRIC_KEYS}
            print(f"  {VARIANT_LABELS[v]:<22}" +
                  "".join(f"{avg[k]:>12.4f}" for k in METRIC_KEYS))


def print_comparison_table(results):
    """
    Ablation comparison table (ablation_study_design.md reporting format):
    Rows=variants, Columns=datasets, Cells= P@1/P@3/P@5/MRR/Recall@GT averaged across targets.
    """
    datasets  = list(DATASETS.keys())
    col_w     = 38
    print(f"\n{'=' * 96}\n  Ablation Comparison Table (each cell: P@1 / P@3 / P@5 / MRR / Recall@GT, averaged across targets)\n{'=' * 96}")
    hdr = f"  {'Variant':<22}" + "".join(f"{d:<{col_w}}" for d in datasets)
    print(hdr)
    print("  " + "-" * (len(hdr) - 2))

    for v in VARIANTS:
        cells = []
        for data in datasets:
            per_t = results[data][v]
            if not per_t:
                cells.append(f"{'N/A':<{col_w}}")
                continue
            avg = {k: float(np.mean([per_t[t][k] for t in per_t])) for k in METRIC_KEYS}
            txt = " / ".join(f"{avg[k]:.3f}" for k in METRIC_KEYS)
            cells.append(f"{txt:<{col_w}}")
        print(f"  {VARIANT_LABELS[v]:<22}" + "".join(cells))


if __name__ == "__main__":
    res = evaluate_all()
    print_per_dataset_avg(res)
    print_comparison_table(res)