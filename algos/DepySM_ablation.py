"""
Ablation study runner script (n_instance = 5, seed = 42)
=========================================================
Based on the updated ablation_study_design.md, this script implements the four
variants V2-V5 that require new computations.
Results for V0 (Full ProDSM) and V1 (w/o ADVR) already exist and are not
regenerated by this script:
    V0 -> res/<target>/inst5/updated_sim_matrix_iter5_p2_k13_d4_c15.json
    V1 -> res/<target>/inst5/sim_matrix.json

Variant mapping (numbering follows the latest ablation_study_design.md)
------------------------------------------------------------------------
  V2  w/o IND-Graph (Emb only) :
      Remove all IND edges (source-side inds.txt + target-side ind_edges.txt)
      when building the AID-Graph; keep only Bridge Edges and FD edges, then
      run PANE embedding without ADVR.
      Output goes to inst5_noind/.
      Self-consistency check: MusicRecordings has no IND, so V2 output should
      be element-wise equal to V1 sim_matrix.json.

  V3  Random Bridge Edges :
      Replace bridge edges with random sampling (build_bridge(random_bridge=True));
      the rest of the AID-Graph (including IND edges) and ADVR remain unchanged.
      Output goes to inst5_randbr/ (the old script used inst5_v/; now unified
      with semantic suffixes).

  V4  FD-only validation :
      Reuse inst5/sim_matrix.json; only re-run ADVR with dep_mode="fd"
      (validate FD only).
      Output: inst5/updated_sim_matrix_fd_only.json.

  V5  IND-only validation :
      Reuse inst5/sim_matrix.json; only re-run ADVR with dep_mode="ind"
      (validate IND only).
      Output: inst5/updated_sim_matrix_ind_only.json.
      Self-consistency check: MusicRecordings has no IND, so V5 output should
      be element-wise equal to V1 sim_matrix.json.

Fairness guarantees
-------------------
1. seed = 42 throughout (fixed upon module import; also fixed inside build_bridge).
2. V4/V5 share the embeddings from V0/V1 (inst5/sim_matrix.json); the only
   difference is the ADVR dependency set.
3. V2/V3 change the graph structure, so embeddings must be re-computed; each
   uses an independent inst_suffix to isolate outputs.
4. All variant target-instance sampling reuses the rng(42)+sorted logic from
   DepySM_batch_more.
5. ADVR hyperparameters are identical to V0 (see REFINE_PARAMS).

Usage (run from the algos/ directory)
--------------------------------------
    cd algos
    python DepySM_ablation.py
"""

