# ── Global fixed random seed ──────────────────────────────────────
RANDOM_SEED = 42
random.seed(RANDOM_SEED)
np.random.seed(RANDOM_SEED)

# ── Global constants ──────────────────────────────────────────────
N_INST        = 5          # Ablation study fixed n_instance = 5
TARGET_PYTHON = "/home/ouyang/anaconda3/envs/PANE/bin/python"
DATA_DIR_BASE = "../data"  # Run from algos/
ITER_NUM      = 5          # emb_sm.py --t
KAPPA         = 1024       # emb_sm.py --kappa

# ADVR hyperparameters: identical to the full method (V0)
REFINE_PARAMS = dict(max_iter=5, patience=2, k_min=1, k_max=3, decay=0.4, ceiling=1.5)

# ── Output filename constants ──────────────────────────────────────
UPDATED_FNAME_FULL  = "updated_sim_matrix_iter5_p2_k13_d4_c15.json"  # V0/V3 ADVR output
V4_FNAME            = "updated_sim_matrix_fd_only.json"               # V4
V5_FNAME            = "updated_sim_matrix_ind_only.json"              # V5

# ── inst_suffix constants ─────────────────────────────────────────
INST_BASE   = f"inst{N_INST}"          # Shared by V0/V1/V4/V5
INST_NOIND  = f"inst{N_INST}_noind"   # V2 independent suffix
INST_RANDBR = f"inst{N_INST}_randbr"  # V3 independent suffix

# ── Dataset configuration ─────────────────────────────────────────
